#!/usr/bin/env node
/**
 * Generate the js_number formatting oracle from real JavaScript.
 *
 * This is PLAN.md section 7.2 applied to the smallest, highest-risk surface: the
 * number-to-string conversion that index strings, schema hashes, and document
 * serialisation all depend on. `String(value)` here is Node's actual
 * implementation, so the committed vector file is the specification — not our
 * reading of ECMA-262.
 *
 * Vectors store the double as a *string* (a shortest round-trip decimal), not a
 * JSON number, so both sides parse the identical bits and no reader can
 * accidentally lose precision in transit.
 *
 *   node xtask/vectors/jsnum.mjs           # write testdata/vectors/jsnum.json
 *   node xtask/vectors/jsnum.mjs --check    # fail if the committed file drifted
 */
import { writeFileSync, readFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, '..', '..');
const outFile = join(repo, 'testdata', 'vectors', 'jsnum.json');

/** High-signal edge cases, chosen because each decides a formatting branch. */
const edgeValues = [
  // Integers and sign handling.
  '0', '-0', '1', '-1', '42', '-42', '255', '65535', '4294967295',
  '9007199254740991', '-9007199254740991', // MAX_SAFE_INTEGER
  '9007199254740992', '-9007199254740992', // 2^53
  '18014398509481984', // 2^54
  '1234567890123456789', // beyond 2^53, still one digit string
  // The 1e21 integer-form / exponent-form boundary.
  '1e19', '1e20', '1e21', '1e22', '1.2e21', '-1e21', '999999999999999900000',
  '1e-0', '1e1', '1e2',
  // The 1e-6 leading-zero / exponent-form boundary.
  '1e-4', '1e-5', '1e-6', '1e-7', '1e-8', '1.5e-7', '-1e-7', '2.2250738585072014e-308',
  // Fractions with awkward decimal expansions.
  '0.1', '0.2', '0.3', '0.5', '0.25', '1.5', '2.5', '0.30000000000000004',
  '0.3333333333333333', '0.6666666666666666', '1.7976931348623157', '23.456',
  // Rounding-at-representation cases.
  '1.2345678901234567', '1.0000000000000002', '4.35', '1.005', '8.795',
  // Extremes.
  '1.7976931348623157e+308', '-1.7976931348623157e+308',
  '5e-324', '-5e-324', '2.5e-308', '1e-300', '1e300',
  // Values where String and JSON.stringify could plausibly diverge.
  '1e21', '1e-7', '0',
  // Two-digit and three-digit exponents, to check the sign is explicit.
  '1e-100', '1e100', '1e-269', '1.5e-100',
  // Subnormal boundary.
  '2.225073858507201e-308', '4.9406564584124654e-324',
];

/** Deterministic pseudo-random bit patterns, so the set is reproducible. */
function* randomDoubles(count) {
  let state = 0x2545f491; // fixed seed: the vector file must be reproducible
  const next = () => {
    state ^= state << 13;
    state >>>= 0;
    state ^= state >> 17;
    state ^= state << 5;
    state >>>= 0;
    return state;
  };
  let emitted = 0;
  let guard = 0;
  while (emitted < count && guard < count * 50) {
    guard += 1;
    // Assemble a random float64 from two 32-bit halves.
    const bits = (BigInt(next()) << 32n) | BigInt(next());
    const view = new DataView(new ArrayBuffer(8));
    view.setBigUint64(0, bits, false);
    const value = view.getFloat64(0, false);
    if (!Number.isFinite(value)) continue;
    // Skip values whose shortest representation is enormous; the point of the
    // random set is breadth of exponents, not stress-testing the string.
    if (value !== 0 && (Math.abs(value) > 1e300 || Math.abs(value) < 1e-300)) continue;
    emitted += 1;
    yield String(value);
  }
}

const values = [];
const seen = new Set();
for (const raw of [...edgeValues, ...randomDoubles(240)]) {
  const value = Number(raw);
  if (Number.isNaN(value) && raw !== 'NaN') {
    throw new Error(`vector input ${raw} did not parse to a number`);
  }
  // Store the canonical shortest round-trip form so both sides see identical bits.
  const canonical = Object.is(value, -0) ? '-0' : String(value);
  if (seen.has(canonical)) continue;
  seen.add(canonical);
  values.push({
    input: canonical,
    jsString: String(value),
    jsJson: JSON.stringify(value),
  });
}

// Non-finite values cannot be represented as a JSON number, but they do reach
// the string formatter, so they are recorded by name.
const specials = [
  { input: 'NaN', jsString: String(Number.NaN), jsJson: JSON.stringify(Number.NaN) },
  { input: 'Infinity', jsString: String(Infinity), jsJson: JSON.stringify(Infinity) },
  { input: '-Infinity', jsString: String(-Infinity), jsJson: JSON.stringify(-Infinity) },
];

const doc = {
  $comment:
    'Generated by xtask/vectors/jsnum.mjs from Node. Do not edit by hand. ' +
    'Regenerate with `make vectors`. Records the observable output of ' +
    'String(x) and JSON.stringify(x) so dxdb-jsnum can be tested against real ' +
    'JavaScript rather than against our reading of ECMA-262 (PLAN.md 7.2).',
  generator: 'xtask/vectors/jsnum.mjs',
  node: process.version,
  format: 'number->string',
  cases: [...values, ...specials],
};

const json = JSON.stringify(doc, null, 2) + '\n';

/**
 * Write or verify the jsnum family. Exported so `generate.mjs` can run every
 * family in one process; the standalone `node xtask/vectors/jsnum.mjs [--check]`
 * behaviour below is unchanged, because this file is the reference the other
 * families are written against.
 */
export function run({ check = process.argv.includes('--check'), repo: repoArg } = {}) {
  const target = repoArg ? join(repoArg, 'testdata', 'vectors', 'jsnum.json') : outFile;
  if (check) {
    let committed;
    try {
      committed = readFileSync(target, 'utf8');
    } catch {
      console.error(`jsnum vectors missing at ${target}; run \`make vectors\``);
      return { ok: false, cases: doc.cases.length };
    }
    // Compare parsed content, not formatting, so a whitespace-only rewrite is not
    // reported as drift. The node version is excluded for the same reason: an
    // upgrade should not fail the build if the numbers are identical.
    const strip = (text) => {
      const parsed = JSON.parse(text);
      delete parsed.node;
      return JSON.stringify(parsed);
    };
    if (strip(committed) !== strip(json)) {
      console.error('jsnum vectors drifted from the current Node output:');
      console.error(`  regenerate with \`make vectors\` and review the diff at ${target}`);
      return { ok: false, cases: doc.cases.length };
    }
    console.log(`jsnum vectors OK (${doc.cases.length} cases)`);
    return { ok: true, cases: doc.cases.length };
  }
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, json);
  console.log(`wrote ${target} (${doc.cases.length} cases, node ${process.version})`);
  return { ok: true, cases: doc.cases.length, bytes: json.length };
}

// Standalone entry point.
if (process.argv[1] && process.argv[1] === fileURLToPath(import.meta.url)) {
  const result = run();
  if (!result.ok) {
    process.exitCode = 1;
  }
}
