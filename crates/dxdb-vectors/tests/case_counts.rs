//! Guards the committed corpus against silent shrinkage.
//!
//! Every other test in the workspace that consumes vectors iterates whatever cases
//! the file contains. If a file is truncated, replaced by an older copy, or written
//! by a generator bug that emits 40 cases instead of 900, those tests keep passing
//! against a smaller corpus and nothing says so.
//!
//! This test is the tripwire. It asserts:
//!
//! 1. every family loads with `deny_unknown_fields` in force, so a generator change
//!    that renames or adds a field fails here rather than being ignored;
//! 2. each family's case count equals the committed expectation;
//! 3. the counts declared *inside* each file match the number of cases actually
//!    present, so an inconsistency between the two cannot hide;
//! 4. every family that should carry upstream provenance does, and it is the
//!    documented pin.
//!
//! When a count changes on purpose, update `EXPECTED_CASE_COUNTS` in the same
//! commit. That edit is the review question: was shrinking the corpus intended?

use dxdb_vectors::{
    index_strings, replication_transcripts, VectorFamily, Vectors, ALL_FAMILIES,
    EXPECTED_CASE_COUNTS,
};

fn expected(family: VectorFamily) -> usize {
    EXPECTED_CASE_COUNTS
        .iter()
        .find(|(f, _)| *f == family)
        .map(|(_, n)| *n)
        .unwrap_or_else(|| panic!("{family} has no entry in EXPECTED_CASE_COUNTS"))
}

#[test]
fn every_family_loads_and_has_the_expected_case_count() {
    let vectors = Vectors::discover();
    let mut total = 0usize;

    for family in ALL_FAMILIES {
        let count = vectors
            .case_count(*family)
            .unwrap_or_else(|e| panic!("loading {family}: {e}"));
        let want = expected(*family);
        assert_eq!(
            count, want,
            "{family} has {count} cases but {want} are expected.\n\
             A vector file that shrank usually means it was truncated, replaced with an \
             older copy, or regenerated by a broken generator. If the change was \
             intentional, update EXPECTED_CASE_COUNTS in crates/dxdb-vectors/src/lib.rs in \
             the same commit so the review sees it."
        );
        total += count;
    }

    assert_eq!(total, 2186, "total corpus size changed: {total} cases");
}

#[test]
fn internal_case_count_fields_agree_with_the_case_arrays() {
    let vectors = Vectors::discover();

    let jsnum = vectors
        .load::<dxdb_vectors::jsnum::Vectors>(VectorFamily::Jsnum)
        .unwrap();
    // jsnum.mjs predates the caseCount field and reports its length at write time.
    assert!(!jsnum.cases.is_empty());

    let idx = vectors
        .load::<index_strings::Vectors>(VectorFamily::IndexStrings)
        .unwrap();
    assert_eq!(idx.case_count, idx.cases.len(), "index-strings caseCount");
    assert_eq!(
        idx.produced_case_count + idx.rejection_case_count,
        idx.cases.len(),
        "index-strings produced + rejection must account for every case"
    );
    assert_eq!(
        idx.rejection_case_count,
        idx.refused().count(),
        "index-strings rejectionCaseCount must equal the number of kind:rejection cases"
    );
    // `producedCaseCount` counts committed cases that produced an index string (i.e.
    // every case except the refusals). `droppedCaseCount` is a separate figure: cases
    // the generator computed but did not commit, to keep the file small. They are not
    // two views of the same number, and conflating them was a wrong assertion here.
    assert_eq!(
        idx.produced_case_count,
        idx.cases.len() - idx.rejection_case_count,
        "index-strings producedCaseCount must equal the committed non-rejection cases"
    );
    assert_eq!(
        idx.produced_case_count + idx.rejection_case_count,
        idx.cases.len(),
        "index-strings produced + rejection must account for every committed case"
    );
    assert_eq!(
        idx.non_rejection().count(),
        idx.produced_case_count,
        "every non-rejection case must be reachable via non_rejection()"
    );
    assert!(
        idx.unexpected_rejections.is_empty(),
        "index-strings recorded an unexpected refusal: {:?}",
        idx.unexpected_rejections
    );
    // The cap means some cases are computed and dropped; that is documented, not a bug.
    assert!(
        idx.dropped_case_count > 0,
        "expected the generator to have dropped cases beyond its cap"
    );

    let hashes = vectors
        .load::<dxdb_vectors::schema_hashes::Vectors>(VectorFamily::SchemaHashes)
        .unwrap();
    assert_eq!(
        hashes.case_count,
        hashes.cases.len(),
        "schema-hashes caseCount"
    );
    assert!(
        hashes.failed_schemas.is_empty(),
        "a fixture schema failed to hash: {:?}",
        hashes.failed_schemas
    );

    let queries = vectors
        .load::<dxdb_vectors::normalised_queries::Vectors>(VectorFamily::NormalisedQueries)
        .unwrap();
    assert_eq!(
        queries.case_count,
        queries.cases.len(),
        "normalised-queries caseCount"
    );

    let bulk = vectors
        .load::<dxdb_vectors::bulk_write_categorization::Vectors>(
            VectorFamily::BulkWriteCategorization,
        )
        .unwrap();
    assert_eq!(
        bulk.case_count,
        bulk.cases.len(),
        "bulk-write-categorization caseCount"
    );

    let sel = vectors
        .load::<dxdb_vectors::selector_matching::Vectors>(VectorFamily::SelectorMatching)
        .unwrap();
    assert_eq!(
        sel.case_count,
        sel.cases.len(),
        "selector-matching caseCount"
    );
    assert_eq!(
        sel.matching_case_count + sel.rejection_case_count,
        sel.cases.len(),
        "selector-matching matching + rejection must account for every case"
    );
    assert_eq!(
        sel.rejection_case_count,
        sel.refused().count(),
        "selector-matching rejectionCaseCount must equal the number of refusals"
    );
    assert!(
        sel.unexpected_rejections.is_empty(),
        "selector-matching recorded an unexpected refusal: {:?}",
        sel.unexpected_rejections
    );

    let repl = vectors
        .load::<replication_transcripts::Vectors>(VectorFamily::ReplicationTranscripts)
        .unwrap();
    assert_eq!(
        repl.case_count,
        repl.case_count(),
        "replication-transcripts caseCount must equal the number of recorded snapshots"
    );
    assert_eq!(
        repl.transaction_count,
        repl.transcripts.len(),
        "replication-transcripts transactionCount"
    );
}

#[test]
fn provenance_is_present_and_matches_the_documented_pin() {
    let vectors = Vectors::discover();

    // Every family records who generated it, and every family except jsnum records
    // the upstream pin it came from. Checked through the typed accessor, so a
    // consumer asserting provenance does not need its own JSON parsing.
    for family in ALL_FAMILIES {
        let p = match *family {
            VectorFamily::Jsnum => vectors
                .load::<dxdb_vectors::jsnum::Vectors>(*family)
                .unwrap()
                .provenance(),
            VectorFamily::IndexStrings => vectors
                .load::<index_strings::Vectors>(*family)
                .unwrap()
                .provenance(),
            VectorFamily::SchemaHashes => vectors
                .load::<dxdb_vectors::schema_hashes::Vectors>(*family)
                .unwrap()
                .provenance(),
            VectorFamily::NormalisedQueries => vectors
                .load::<dxdb_vectors::normalised_queries::Vectors>(*family)
                .unwrap()
                .provenance(),
            VectorFamily::BulkWriteCategorization => vectors
                .load::<dxdb_vectors::bulk_write_categorization::Vectors>(*family)
                .unwrap()
                .provenance(),
            VectorFamily::SelectorMatching => vectors
                .load::<dxdb_vectors::selector_matching::Vectors>(*family)
                .unwrap()
                .provenance(),
            VectorFamily::ReplicationTranscripts => vectors
                .load::<replication_transcripts::Vectors>(*family)
                .unwrap()
                .provenance(),
            VectorFamily::ErrorVectors => vectors
                .load::<dxdb_vectors::error_vectors::Vectors>(*family)
                .unwrap()
                .provenance(),
        };

        assert!(
            !p.generator.is_empty(),
            "{family} has an empty generator field"
        );
        assert!(!p.comment.is_empty(), "{family} has an empty $comment");

        if *family == VectorFamily::Jsnum {
            // jsnum only needs Node; claiming an upstream pin would be a lie.
            assert!(
                !p.is_upstream(),
                "jsnum should not claim upstream provenance, got {:?}",
                p.rxdb_commit
            );
        } else {
            assert!(
                p.matches_documented_pin(),
                "{family} was not generated from the documented pin \
                 (commit {:?}, version {:?}); regenerate with `make vectors`",
                p.rxdb_commit,
                p.rxdb_version
            );
        }
    }
}

#[test]
fn schema_hash_relations_resolve_and_are_self_consistent() {
    let vectors = Vectors::discover();
    let hashes = vectors
        .load::<dxdb_vectors::schema_hashes::Vectors>(VectorFamily::SchemaHashes)
        .unwrap();

    assert!(
        !hashes.relations.is_empty(),
        "the relations block is the only part of this family that asserts properties of \
         the hash function; losing it would leave per-case hashing as the whole check"
    );

    for relation in &hashes.relations {
        // Every endpoint must resolve to a declared case. The generator now refuses to
        // emit a relation that does not, so a failure here means the file was hand-edited.
        let (a, b) = relation.resolve(&hashes).unwrap_or_else(|| {
            panic!(
                "relation {} names an endpoint that is not a case (a={:?}, b={:?})",
                relation.why, relation.a, relation.b
            )
        });

        // The relation's own hashes must be the cases' hashes, not something else.
        assert_eq!(
            Some(relation.hash_a.as_str()),
            a.hash.as_deref(),
            "relation {} recorded hashA that is not case {}'s hash",
            relation.why,
            relation.a
        );
        assert_eq!(
            Some(relation.hash_b.as_str()),
            b.hash.as_deref(),
            "relation {} recorded hashB that is not case {}'s hash",
            relation.why,
            relation.b
        );

        // And the `equal` flag must agree with those hashes.
        assert!(
            relation.is_self_consistent(),
            "relation {} claims equal={} but hashA={} and hashB={}",
            relation.why,
            relation.equal,
            relation.hash_a,
            relation.hash_b
        );
    }

    // The positive and negative classes must both be present and correct: a block that
    // only proved insensitivity would let a port hash everything the same and pass.
    let positives: Vec<_> = hashes
        .relations
        .iter()
        .filter(|r| r.why.contains("does-not-change") || r.why.contains("equals-implicit"))
        .collect();
    let negatives: Vec<_> = hashes
        .relations
        .iter()
        .filter(|r| r.why.contains("changes-hash"))
        .collect();
    assert!(
        !positives.is_empty(),
        "no 'does not change the hash' relations"
    );
    assert!(!negatives.is_empty(), "no 'changes the hash' relations");
    for relation in &positives {
        assert!(
            relation.equal,
            "positive relation {} is not equal",
            relation.why
        );
    }
    for relation in &negatives {
        assert!(
            !relation.equal,
            "negative relation {} is equal, so the property it asserts is false",
            relation.why
        );
    }

    // The specific relation this was fixed for: the key-order case must be a genuine
    // permutation of the baseline, and must hash identically to it.
    let order = hashes
        .relations
        .iter()
        .find(|r| r.why == "key-order-does-not-change-hash")
        .expect("key-order relation missing");
    let (baseline, permuted) = order.resolve(&hashes).unwrap();
    assert_eq!(
        baseline.hash, permuted.hash,
        "a key-order permutation changed the hash"
    );
    assert!(
        baseline.hash.is_some(),
        "the key-order baseline must have hashed, not been rejected"
    );
    // The two inputs must be the same schema, so the difference between them is only
    // insertion order. `serde_json` with `preserve_order` keeps the original order in
    // `Value`, so the key orders can be compared directly.
    let base_keys: Vec<_> = baseline
        .input
        .as_object()
        .unwrap()
        .keys()
        .cloned()
        .collect();
    let perm_keys: Vec<_> = permuted
        .input
        .as_object()
        .unwrap()
        .keys()
        .cloned()
        .collect();
    let mut sorted_base = base_keys.clone();
    let mut sorted_perm = perm_keys.clone();
    sorted_base.sort();
    sorted_perm.sort();
    assert_eq!(
        sorted_base, sorted_perm,
        "the key-order case is not a permutation: different key sets"
    );
    assert_ne!(
        base_keys, perm_keys,
        "the key-order case has the same insertion order as the baseline, so it does not \
         test what its name claims"
    );
    assert_eq!(
        baseline.input, permuted.input,
        "the key-order case differs in a VALUE, not just in key order, so it is a \
         different schema and proves nothing about order-insensitivity"
    );
}

#[test]
fn every_schema_name_used_by_another_family_resolves_to_a_fixture_input() {
    // `index-strings` and `normalised-queries` refer to a schema by name per case
    // instead of repeating it. This family is where those names resolve, so a name
    // that does not resolve forces a consumer to hand-copy the schema literal — which
    // is what two downstream test files used to do, including a hand-written
    // `averageSchema`.
    let vectors = Vectors::discover();
    let hashes = vectors
        .load::<dxdb_vectors::schema_hashes::Vectors>(VectorFamily::SchemaHashes)
        .unwrap();
    let fixtures = hashes.fixture_inputs();

    let mut checked = 0;
    for family in [VectorFamily::IndexStrings, VectorFamily::NormalisedQueries] {
        let text = std::fs::read_to_string(vectors.path(family)).unwrap();
        let doc: serde_json::Value = serde_json::from_str(&text).unwrap();
        let cases = doc["cases"].as_array().expect("cases array");
        for case in cases {
            let Some(name) = case["schema"].as_str() else {
                continue;
            };
            assert!(
                fixtures.contains_key(name),
                "{} names the schema {name:?}, which is not a resolvable fixture in the \
                 schema-hashes family. A consumer would have to copy that schema by hand, \
                 which is the drift this accessor exists to remove. If it is a function \
                 export upstream (like `averageSchema`), it must be emitted as a case.",
                family
            );
            checked += 1;
        }
    }
    assert!(
        checked > 0,
        "no cross-family schema references were found to check"
    );

    // The specific case that used to be missing: a function export whose `title` embeds
    // `randomString(5)`, which the old object-only enumeration filtered out.
    assert!(
        fixtures.contains_key("averageSchema"),
        "`averageSchema` must be a case: `normalised-queries` refers to it, and its only \
         alternative is a hand-copied literal. Its random title is stable because the \
         generator seeds Math.random."
    );
}
