/**
 * Capability probe.
 *
 * Every value here is *measured in the running engine*, never inferred from a
 * browser version string. The results are the evidence cited in
 * docs/lanes/m4-browser-plan.md for:
 *
 *   - the OPFS worker-vs-main-thread decision (PLAN.md 5.4:
 *     `createSyncAccessHandle` is worker-only), and
 *   - which WASM features the shipped core may use unconditionally (PLAN.md
 *     3.4's capability matrix).
 */

/**
 * @typedef {{ name: string, ok: boolean, detail: string }} ProbeResult
 */

/** @returns {ProbeResult} */
function probe(name, fn) {
  try {
    const value = fn();
    return typeof value === 'object' && value !== null && 'ok' in value
      ? { name, ok: Boolean(value.ok), detail: String(value.detail ?? '') }
      : { name, ok: Boolean(value), detail: value ? 'present' : 'absent' };
  } catch (err) {
    return { name, ok: false, detail: `threw: ${String(err && err.message || err)}` };
  }
}

/**
 * WebAssembly feature probes.
 *
 * A feature is "usable unconditionally" only if all three browsers report it
 * here. `validate()` is used rather than instantiating, so the probe does not
 * run any code — it only asks whether the engine accepts the byte encoding.
 *
 * @param {string} bytesBase64 a tiny module encoded with the feature under test
 */
function wasmFeature(bytesBase64) {
  return () => {
    if (typeof WebAssembly === 'undefined') return { ok: false, detail: 'no WebAssembly' };
    const bytes = Uint8Array.from(atob(bytesBase64), (c) => c.charCodeAt(0));
    // Throws a CompileError (or returns false in old engines) when unsupported.
    const valid = WebAssembly.validate(bytes);
    return { ok: valid, detail: valid ? 'accepted' : 'rejected by validate()' };
  };
}

/**
 * Minimal wasm modules that *require* the feature under test to validate.
 *
 * These are hand-encoded on purpose: pulling a dependency in to answer "does
 * this engine support simd128" would make the probe itself the thing that needs
 * probing. Each was generated by a small builder and verified with a raw
 * `WebAssembly.validate()` in Node before being pasted here; a malformed probe
 * is worse than no probe, because it reports a false negative for a feature the
 * engine actually has.
 *
 * Contents, for review without decoding the base64:
 *   baseline    (module (func (result i32) i32.const 7))
 *   multivalue  (module (func (result i32 i32) i32.const 1 i32.const 2))
 *   simd128     (module (func (result v128) v128.const i32x4 1 2 3 4))
 *   bulk-memory (module (memory 1) (func (memory.copy (i32.const 0) (i32.const 0) (i32.const 0))))
 */
const WASM_PROBES = {
  baseline: 'AGFzbQEAAAABBQFgAAF/AwIBAAoGAQQAQQcL',
  multivalue: 'AGFzbQEAAAABBgFgAAJ/fwMCAQAKCAEGAEEBQQIL',
  simd128: 'AGFzbQEAAAABBQFgAAF7AwIBAAoWARQA/QwBAAAAAgAAAAMAAAAEAAAACw==',
  bulkMemory: 'AGFzbQEAAAABBAFgAAADAgEABQMBAAEKDgEMAEEAQQBBAPwKAAAL',
};

/**
 * Run every probe. The worker-only sync-handle probe is async, so this returns
 * a promise even though most probes are synchronous.
 *
 * @returns {Promise<{ probes: ProbeResult[], environment: Record<string, unknown> }>}
 */
export async function runCapabilityProbe() {
  /** @type {ProbeResult[]} */
  const probes = [];

  probes.push(
    probe('indexedDB', () => {
      const ok = typeof indexedDB !== 'undefined' && indexedDB !== null;
      // `indexedDB.version` is 0/undefined until a database is opened, so it is
      // reported only when it is meaningful rather than as a fake identifier.
      if (!ok) return { ok: false, detail: 'absent' };
      const version = indexedDB.version;
      return { ok: true, detail: version ? `version ${version}` : 'present (no database open)' };
    }),
  );

  probes.push(
    probe('localStorage', () => {
      const ok = typeof localStorage !== 'undefined' && localStorage !== null;
      // Access, not just existence: Safari in a partitioned/blocked context
      // throws on access while leaving the global defined.
      if (!ok) return { ok: false, detail: 'absent' };
      localStorage.setItem('dxdb-probe', '1');
      localStorage.removeItem('dxdb-probe');
      return { ok: true, detail: 'read/write ok' };
    }),
  );

  probes.push(
    probe('BroadcastChannel', () => typeof BroadcastChannel !== 'undefined'),
  );

  probes.push(probe('navigator.locks', () => typeof navigator?.locks?.request === 'function'));

  probes.push(
    probe('navigator.storage.getDirectory (OPFS)', () => {
      const ok = typeof navigator?.storage?.getDirectory === 'function';
      return { ok, detail: ok ? 'OPFS root accessible' : 'absent' };
    }),
  );

  probes.push(
    probe('createSyncAccessHandle on main thread', () => {
      // This is the load-bearing one. It MUST be absent/false on the main
      // thread: `createSyncAccessHandle()` is exposed only to dedicated
      // workers (PLAN.md 5.4), which is why the fast OPFS path is a worker
      // story. If a browser ever exposes it here, that is news and the plan
      // changes — hence we record the answer instead of assuming it.
      const proto =
        typeof FileSystemFileHandle !== 'undefined'
          ? FileSystemFileHandle.prototype
          : undefined;
      const ok = typeof proto?.createSyncAccessHandle === 'function';
      return {
        ok,
        detail: ok
          ? 'EXPOSED ON MAIN THREAD (unexpected — re-check the OPFS plan)'
          : 'not exposed on main thread (expected)',
      };
    }),
  );

  probes.push(await probeSyncHandleInWorker());

  probes.push(
    probe('createWritable on main thread', () => {
      // The async OPFS path, which is the documented main-thread fallback.
      const proto =
        typeof FileSystemFileHandle !== 'undefined'
          ? FileSystemFileHandle.prototype
          : undefined;
      const ok = typeof proto?.createWritable === 'function';
      return { ok, detail: ok ? 'async write path available' : 'absent' };
    }),
  );

  probes.push(probe('wasm baseline', wasmFeature(WASM_PROBES.baseline)));
  probes.push(probe('wasm simd128', wasmFeature(WASM_PROBES.simd128)));
  probes.push(probe('wasm multivalue', wasmFeature(WASM_PROBES.multivalue)));
  probes.push(probe('wasm bulk-memory', wasmFeature(WASM_PROBES.bulkMemory)));

  return {
    probes,
    environment: {
      userAgent: navigator.userAgent,
      // Chromium reports the real version here; WebKit reports the Safari
      // version, which is what we want to cite in the plan.
      platform: navigator.platform ?? 'unknown',
      language: navigator.language,
      href: location.href,
    },
  };
}

/**
 * Re-run the sync-handle probe from inside a dedicated worker.
 *
 * The point is the *difference* between this and the main-thread result: it is
 * what makes "worker-only" a measured fact in the engines we ship to.
 *
 * @returns {Promise<ProbeResult>}
 */
async function probeSyncHandleInWorker() {
  const name = 'createSyncAccessHandle in dedicated worker';

  if (typeof Worker === 'undefined') {
    return { name, ok: false, detail: 'no Worker constructor' };
  }

  let worker;
  try {
    // `import.meta.url` is this module's URL (demo/harness/capabilities.js), so
    // the worker is its *sibling*: './sync-handle-worker.js'. Getting this wrong
    // yields a 404 and an opaque "worker error: unknown", which is why the
    // error path below also reports the filename.
    worker = new Worker(new URL('./sync-handle-worker.js', import.meta.url), {
      type: 'module',
    });
  } catch (err) {
    return { name, ok: false, detail: `worker construction threw: ${String(err)}` };
  }

  try {
    return await new Promise((resolve) => {
      const timer = setTimeout(
        () => resolve({ name, ok: false, detail: 'worker timed out after 5s' }),
        5000,
      );
      worker.onmessage = (ev) => {
        clearTimeout(timer);
        const data = ev.data ?? {};
        resolve({
          name,
          ok: Boolean(data.ok),
          detail: String(data.detail ?? '(no detail)'),
        });
      };
      worker.onerror = (ev) => {
        clearTimeout(timer);
        // A module worker that fails to load fires this with an empty message
        // and puts the useful part in `filename`. Report both, because
        // "worker error: unknown" is indistinguishable from a real probe bug.
        resolve({
          name,
          ok: false,
          detail: `worker error: ${ev.message || '(no message)'}${ev.filename ? ` at ${ev.filename}:${ev.lineno ?? '?'}` : ''}`,
        });
      };
    });
  } finally {
    worker.terminate();
  }
}
